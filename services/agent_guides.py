def load_guide(topics) -> dict:
    if isinstance(topics, str):
        topics = [topics]
    picked = [t for t in (topics or []) if t in GUIDES]
    if not picked:
        return {"error": f"未知主题, 可选: {', '.join(GUIDES)}"}
    return {"guides": {t: GUIDES[t][1] for t in picked}}
